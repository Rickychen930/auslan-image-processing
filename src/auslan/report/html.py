"""Render the report's Markdown tables as one self-contained HTML page."""

from __future__ import annotations

import html
import re
from pathlib import Path

import pandas as pd

SECTIONS = (
    ("Headline results (Table 9)", "table9.md"),
    ("Success criteria", "success_criteria.md"),
    ("Same dataset against another dataset (E2)", "cross_dataset.md"),
    ("Significance and the gain from ASL training", "significance.md"),
    ("Training cost and speed", "cost.md"),
    ("Design alternatives (E5)", "variants.md"),
    ("Image style (E6)", "style_effect.md"),
    ("Image size (E7)", "image_size.md"),
    ("Most confused letters (E4)", "confused_pairs.md"),
    ("Hand detection and failures", "detection_rates.md"),
)
STYLE = """
:root { color-scheme: light dark; --line: #8884; --accent: #2a6fdb; }
body { font: 15px/1.5 system-ui, sans-serif; max-width: 1000px;
       margin: 2rem auto; padding: 0 1rem; }
h1 { margin-bottom: .2rem } h2 { margin-top: 2.2rem; border-bottom: 2px solid var(--accent); }
table { border-collapse: collapse; margin: .8rem 0; display: block; overflow-x: auto; }
th, td { border: 1px solid var(--line); padding: .3rem .7rem; text-align: left;
         white-space: nowrap; }
th { background: #8882; } code { background: #8882; padding: 0 .25rem; border-radius: 3px; }
.note { color: #888; }
"""


def _inline(text: str) -> str:
    text = html.escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    return re.sub(r"`(.+?)`", r"<code>\1</code>", text)


def _table(lines: list[str]) -> str:
    rows = [[cell.strip() for cell in line.strip().strip("|").split("|")] for line in lines]
    head = "".join(f"<th>{_inline(cell)}</th>" for cell in rows[0])
    body = "".join(
        "<tr>" + "".join(f"<td>{_inline(cell)}</td>" for cell in row) + "</tr>" for row in rows[2:]
    )
    return f"<table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table>"


def markdown_to_html(text: str) -> str:
    """Convert the small Markdown subset the report writes: tables, ### headings, bullets."""
    blocks: list[str] = []
    table: list[str] = []
    bullets: list[str] = []

    def flush() -> None:
        if table:
            blocks.append(_table(table))
        if bullets:
            blocks.append("<ul>" + "".join(f"<li>{_inline(b)}</li>" for b in bullets) + "</ul>")
        table.clear()
        bullets.clear()

    for line in text.splitlines():
        if line.startswith("|"):
            table.append(line)
            continue
        if line.startswith("- "):
            bullets.append(line[2:])
            continue
        flush()
        if line.startswith("###"):
            blocks.append(f"<h3>{_inline(line.lstrip('# '))}</h3>")
        elif line.strip():
            blocks.append(f"<p>{_inline(line)}</p>")
    flush()
    return "\n".join(blocks)


def render_index(report_dir: Path) -> Path:
    """Write ``index.html`` next to the report files and return its path."""
    parts = []
    for title, filename in SECTIONS:
        path = report_dir / filename
        if path.exists():
            parts.append(f"<h2>{html.escape(title)}</h2>\n{markdown_to_html(path.read_text())}")
    curve = report_dir / "k_curve.csv"
    if curve.exists() and len(curve_frame := pd.read_csv(curve)):
        table = curve_frame.round(3).to_html(index=False, border=0)
        parts.append(f"<h2>Examples per letter against macro-F1 (E3)</h2>\n{table}")
    page = (
        f"<!doctype html><meta charset=utf-8><title>Auslan results</title><style>{STYLE}</style>"
        "<h1>Auslan fingerspelling results</h1>"
        "<p class=note>Generated by <code>auslan report</code>; every number comes from "
        "<code>artifacts/results.jsonl</code>.</p>" + "\n".join(parts)
    )
    target = report_dir / "index.html"
    target.write_text(page)
    return target
